const ABSENT_VALUES = ['not included', 'not allowed', 'non-refundable'];

let instanceCount = 0;

function el(tag, className, content) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (content !== undefined && content !== null) node.textContent = content;
  return node;
}

function icon(name, className) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('class', className);
  svg.setAttribute('viewBox', '0 0 16 16');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  (ICONS[name] || []).forEach(([tag, attrs]) => {
    const shape = document.createElementNS(SVG_NS, tag);
    Object.entries(attrs).forEach(([key, value]) => shape.setAttribute(key, value));
    svg.append(shape);
  });
  return svg;
}

function hasValue(value) {
  if (value === undefined || value === null) return false;
  return String(value).trim() !== '';
}

function text(value) {
  return hasValue(value) ? String(value) : '';
}

function fareKey(record) {
  return text(record?.fare_id).trim().toLowerCase();
}

function sameId(a, b) {
  if (!hasValue(a) || !hasValue(b)) return false;
  return String(a).trim().toLowerCase() === String(b).trim().toLowerCase();
}

function statusOf(value) {
  const v = text(value).trim().toLowerCase();
  if (v === 'included' || /^\d+ included$/.test(v)) return 'included';
  if (v.startsWith('available for a fee')) return 'fee';
  if (ABSENT_VALUES.includes(v)) return 'absent';
  return 'other';
}

function safeHref(url) {
  if (!hasValue(url)) return null;
  try {
    const parsed = new URL(String(url));
    return parsed.protocol === 'https:' || parsed.protocol === 'tel:' ? parsed.href : null;
  } catch (e) {
    return null;
  }
}

function canUseBridge(bridge) {
  return Boolean(bridge?.isConnected) && bridge.hostContext?.preview !== true;
}

function valueCell(value, fareName) {
  const status = statusOf(value);
  const dd = el('dd', `benefit-value is-${status}`);
  if (status !== 'other') dd.append(icon(status, 'status-icon'));
  if (fareName) dd.append(el('span', 'visually-hidden', `${fareName}: `));
  dd.append(el('span', '', text(value)));
  return dd;
}

function groupSummary(name, tally) {
  const summary = el('summary', 'group-summary');
  summary.append(el('span', 'group-name', name));
  if (tally) summary.append(el('span', 'group-tally', tally));
  summary.append(icon('chevron', 'group-chevron'));
  return summary;
}

function buildLedger(first, second) {
  const ledger = el('section', 'ledger');
  ledger.tabIndex = 0;
  ledger.setAttribute('aria-label', second
    ? `${text(first.name)} and ${text(second.name)} benefits`
    : `${text(first.name)} benefits`);

  if (second) {
    const head = el('div', 'pair-head');
    head.setAttribute('aria-hidden', 'true');
    head.append(el('span', 'pair-head-label', 'Benefit'));
    head.append(el('span', 'pair-head-name', text(first.name)));
    head.append(el('span', 'pair-head-name', text(second.name)));
    ledger.append(head);
  }

  GROUPS.forEach((group) => {
    const rows = group.rows.filter(([, key]) => hasValue(first[key])
      || (second && hasValue(second[key])));
    if (!rows.length) return;

    const details = el('details', 'ledger-group');
    details.open = group.open;
    const list = el('dl', 'benefit-list');
    let included = 0;
    let differs = 0;

    rows.forEach(([label, key]) => {
      const row = el('div', second ? 'benefit-row is-pair' : 'benefit-row');
      const dt = el('dt', 'benefit-label');
      dt.append(el('span', '', label));
      if (second) {
        const isDifferent = text(first[key]).trim().toLowerCase()
          !== text(second[key]).trim().toLowerCase();
        if (isDifferent) {
          differs += 1;
          dt.append(el('span', 'differs-mark', 'Differs'));
        }
        row.append(
          dt,
          valueCell(first[key], text(first.name)),
          valueCell(second[key], text(second.name)),
        );
      } else {
        if (statusOf(first[key]) === 'included') included += 1;
        row.append(dt, valueCell(first[key]));
      }
      list.append(row);
    });

    const tally = second
      ? `Differs on ${differs} of ${rows.length}`
      : `${included} of ${rows.length} included`;
    details.append(groupSummary(group.name, tally), list);
    ledger.append(details);
  });

  [first, second].filter(Boolean).forEach((record) => {
    if (!hasValue(record.description)) return;
    const details = el('details', 'ledger-group');
    details.append(
      groupSummary(text(record.name) ? `About ${text(record.name)}` : 'About this fare'),
      el('p', 'fare-about', text(record.description)),
    );
    ledger.append(details);
  });

  return ledger;
}

function bookPrompt(record, args) {
  let prompt = `Start booking with the ${text(record.name)} fare (fare_id ${text(record.fare_id)})`;
  if (hasValue(args.search_context_id)) prompt += ` for search context ${text(args.search_context_id)}`;
  return prompt;
}

function bookButton(record, args, className, label, bridge) {
  const button = el('button', className, label);
  button.type = 'button';
  if (hasValue(record.fare_id)) button.dataset.fareId = text(record.fare_id);
  button.addEventListener('click', () => {
    if (!bridge?.isConnected) return;
    bridge.sendMessage(bookPrompt(record, args));
  });
  return button;
}

function sourceLink(record, bridge) {
  const href = safeHref(record.source_url);
  if (!href) return null;
  const link = el('a', 'button-secondary');
  link.href = href;
  if (href.startsWith('https:')) {
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
  }
  link.append(document.createTextNode(`${text(record.name)} on westjet.com`));
  link.append(icon('external', 'button-icon'));
  link.append(el('span', 'visually-hidden', ' (opens in a new tab)'));
  link.addEventListener('click', (event) => {
    if (!bridge?.isConnected || !href.startsWith('https:')) return;
    event.preventDefault();
    bridge.openLink(href);
  });
  return link;
}

function messageView(root, title, message) {
  const head = el('header', 'compare-head');
  const fixed = el('div', 'fare-fixed');
  fixed.append(el('h1', 'fare-name', title));
  head.append(fixed);
  const note = el('p', 'compare-message', message);
  note.setAttribute('role', 'status');
  root.append(head, note);
}

export default async function decorate(block, bridge) {
  instanceCount += 1;
  const selectId = `${ACTION_NAME}-second-fare-${instanceCount}`;
  const hintId = `${ACTION_NAME}-pick-hint-${instanceCount}`;
  const nameId = `${ACTION_NAME}-fare-name-${instanceCount}`;
  const state = { candidates: null, first: null, args: {} };

  function render(result, { selectedId = '', status = '', loading = false } = {}) {
    const args = result && typeof result.arguments === 'object' && result.arguments
      ? result.arguments : {};
    const records = Array.isArray(result?.records)
      ? result.records.filter((r) => r && typeof r === 'object') : [];
    const root = el('div', 'fare-compare');

    if (!records.length) {
      messageView(root, 'Compare WestJet fares', 'No fares were returned.');
      block.replaceChildren(root);
      return;
    }

    let first = null;
    let second = null;
    const isPair = hasValue(args.second_fare_id) && records.length === 2
      && sameId(records[0].fare_id, args.first_fare_id)
      && sameId(records[1].fare_id, args.second_fare_id)
      && fareKey(records[0]) !== fareKey(records[1]);

    if (isPair) {
      [first, second] = records;
      if (!state.candidates || !state.first || fareKey(state.first) !== fareKey(first)) {
        state.candidates = [second];
        state.first = first;
      }
    } else {
      first = hasValue(args.first_fare_id)
        ? records.find((r) => sameId(r.fare_id, args.first_fare_id)) : null;
      if (!first) {
        messageView(root, 'Compare WestJet fares', 'We couldn\'t compare those fares. Choose another fare or ask in the chat.');
        block.replaceChildren(root);
        return;
      }
      const seen = new Set([fareKey(first)]);
      state.candidates = records.filter((r) => {
        const key = fareKey(r);
        if (!key || seen.has(key)) return false;
        seen.add(key);
        return true;
      });
      state.first = first;
    }
    state.args = args;

    root.setAttribute('role', 'region');
    root.setAttribute('aria-labelledby', nameId);

    // Header band: fixed first fare and the second-fare picker
    const head = el('header', 'compare-head');
    const fixed = el('div', 'fare-fixed');
    const title = el('h1', 'fare-name');
    title.id = nameId;
    title.append(el('span', '', text(first.name)));
    if (second) {
      title.append(el('span', 'fare-versus', ' compared with '));
      title.append(el('span', '', text(second.name)));
    }
    fixed.append(title);
    const tags = el('ul', 'fare-tags');
    tags.setAttribute('aria-label', 'Fare details');
    if (hasValue(first.cabin)) tags.append(el('li', 'badge', text(first.cabin)));
    if (first.is_flex === true) tags.append(el('li', 'badge', 'Flex'));
    if (tags.children.length) fixed.append(tags);
    head.append(fixed);

    const pick = el('div', 'compare-pick');
    const candidates = state.candidates || [];
    const statusLine = el('p', 'pick-status', status);
    statusLine.setAttribute('role', 'status');
    statusLine.hidden = !status;

    if (candidates.length) {
      const label = el('label', 'pick-label', 'Compare with another');
      label.htmlFor = selectId;
      const control = el('div', 'pick-control');
      const select = el('select', 'pick-select');
      select.id = selectId;
      select.name = 'second_fare_id';
      select.setAttribute('aria-describedby', hintId);
      const chosen = selectedId || (second ? text(second.fare_id) : '');
      const placeholder = el('option', '', 'Choose a fare');
      placeholder.value = '';
      placeholder.disabled = true;
      placeholder.selected = !chosen;
      select.append(placeholder);
      candidates.forEach((record) => {
        const option = el('option', '', text(record.name) || text(record.fare_id));
        option.value = text(record.fare_id);
        option.selected = sameId(option.value, chosen);
        select.append(option);
      });
      select.disabled = loading;
      control.append(select, icon('chevron', 'pick-chevron'));
      const hint = el('p', 'pick-hint', 'See both fares side by side, benefit by benefit.');
      hint.id = hintId;
      pick.append(label, control, hint, statusLine);

      select.addEventListener('change', async () => {
        const secondId = select.value;
        if (!secondId || !canUseBridge(bridge)) return;
        const callArgs = { first_fare_id: text(first.fare_id), second_fare_id: secondId };
        if (hasValue(state.args.search_context_id)) {
          callArgs.search_context_id = state.args.search_context_id;
        }
        const current = result;
        render(current, { selectedId: secondId, status: 'Loading comparison', loading: true });
        try {
          const response = await bridge.callTool(ACTION_NAME, callArgs);
          const content = response?.structuredContent;
          const recs = Array.isArray(content?.records) ? content.records : [];
          const ok = !response?.isError && recs.length === 2
            && sameId(recs[0]?.fare_id, callArgs.first_fare_id)
            && sameId(recs[1]?.fare_id, secondId);
          if (ok) {
            render({ arguments: { ...callArgs, ...(content.arguments || {}) }, records: recs });
          } else {
            render(current, { selectedId: secondId, status: 'We couldn\'t compare those fares. Choose another fare or ask in the chat.' });
          }
        } catch (e) {
          render(current, { selectedId: secondId, status: 'We couldn\'t compare those fares. Choose another fare or ask in the chat.' });
        }
      });
    } else {
      pick.append(el('p', 'pick-empty', 'No other fare to compare with.'), statusLine);
    }
    head.append(pick);

    // Actions
    const actions = el('footer', 'compare-actions');
    if (second) {
      actions.append(
        bookButton(first, args, 'button-primary', `Book ${text(first.name)}`, bridge),
        bookButton(second, args, 'button-secondary', `Book ${text(second.name)}`, bridge),
      );
    } else {
      actions.append(bookButton(first, args, 'button-primary', `Book with ${text(first.name)}`, bridge));
      const link = sourceLink(first, bridge);
      if (link) actions.append(link);
    }

    root.append(head, buildLedger(first, second), actions);
    block.replaceChildren(root);
  }

  const connected = canUseBridge(bridge);
  let result = PREVIEW_RESULT;
  if (connected) {
    try {
      result = (await bridge.toolResult)?.structuredContent || { records: [] };
    } catch (e) {
      result = { records: [] };
    }
  }

  if (bridge?.isConnected && bridge.hostContext?.theme) {
    block.dataset.theme = bridge.hostContext.theme;
  }
  if (bridge?.isConnected && typeof bridge.onContextChange === 'function') {
    bridge.onContextChange((context) => {
      if (context?.theme) block.dataset.theme = context.theme;
    });
  }

  render(result);

  if (bridge?.isConnected && typeof bridge.autoResize === 'function') {
    bridge.autoResize(block);
  }
}
